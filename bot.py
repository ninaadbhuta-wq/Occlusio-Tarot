async def send_random_card(message: types.Message):
    user_id = message.from_user.id
    # Определяем сегодняшнюю дату по Москве
    today_date = datetime.now(MSK).strftime("%Y-%m-%d")

    # Проверяем, тянул ли пользователь карту сегодня
    if user_last_draw.get(user_id) == today_date:
        await message.answer(
            "🌙 Ты уже вытянул(а) свою карту на сегодня. Звёзды любят терпение — возвращайся завтра после полуночи за новым посланием!",
            reply_markup=keyboard
        )
        return

    # Если еще не тянул — записываем сегодняшнюю дату и выдаем карту
    user_last_draw[user_id] = today_date
    card = random.choice(TAROT_CARDS)
    photo = FSInputFile(card["image"].replace("cards/", ""))
    caption_text = f"🔮 <b>{card['title']}</b>\n\n{card['message']}"

    await message.answer_photo(
        photo=photo,
        caption=caption_text,
        parse_mode="HTML",
        reply_markup=keyboard
    )

@dp.message(CommandStart())
async def cmd_start(message: types.Message):
    await message.answer("Добро пожаловать в мир магии! Перемешиваю колоду... ✨")
    await send_random_card(message)

@dp.message(F.text == "✨ Вытянуть карту дня")
async def cmd_draw_card(message: types.Message):
    await send_random_card(message)

